"""Illustrate the cleaning step: raw vs smoothed altitude/grade, stop durations.

Usage:
    python scripts/report_cleaning.py
Writes reports/cleaning.md and reports/figures/cleaning_*.png
"""

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from cycling_coach import config
from cycling_coach.plotting import MUTED, SERIES, label, save, style_axes, title

FIG = config.REPORTS_DIR / "figures"


def plot_altitude_and_grade(raw: pd.DataFrame, clean: pd.DataFrame, path) -> None:
    """Profile of a 3 km climbing section (distance axis only, no location)."""
    start = clean.loc[clean["grade"].idxmax(), "distance_m"] - 1500
    window = lambda d: d[(d["distance_m"] >= start) & (d["distance_m"] <= start + 3000)]  # noqa: E731
    r, c = window(raw), window(clean)
    km_r, km_c = (r["distance_m"] - start) / 1000, (c["distance_m"] - start) / 1000

    fig, (ax1, ax2) = plt.subplots(2, 1, figsize=(10, 6), sharex=True)
    ax1.plot(km_r, r["altitude_m"], color=MUTED, linewidth=1, label="Raw")
    ax1.plot(km_c, c["altitude_smooth_m"], color=SERIES[0], linewidth=2, label="Smoothed")
    style_axes(ax1)
    label(ax1, y="Altitude (m)")
    title(ax1, "Altitude and grade on a 3 km climb section: raw vs cleaned")
    ax1.legend(frameon=False)

    ax2.plot(km_r, (r["grade_raw"] * 100).clip(-60, 60), color=MUTED, linewidth=0.8, label="Raw (per second)")
    ax2.plot(km_c, c["grade"] * 100, color=SERIES[0], linewidth=2, label="Cleaned (50 m window)")
    style_axes(ax2)
    label(ax2, x="Distance (km)", y="Grade (%)")
    ax2.legend(frameon=False)
    save(fig, path)


def plot_stop_durations(stops: pd.DataFrame, path) -> None:
    fig, ax = plt.subplots(figsize=(10, 3.5))
    ax.hist(stops["duration_s"].clip(upper=180), bins=np.arange(0, 185, 5),
            color=SERIES[0], edgecolor="white", linewidth=1)
    style_axes(ax)
    label(ax, x="Stop duration (s, longer stops shown at 180)", y="Stops")
    title(ax, "How long each stop lasts (all rides)")
    save(fig, path)


def main() -> None:
    rides = pd.read_parquet(config.PROCESSED_DIR / "rides.parquet")
    stops = pd.read_parquet(config.PROCESSED_DIR / "stops.parquet")
    climb = rides.sort_values("elevation_gain_m").iloc[-1]
    raw = pd.read_parquet(config.INTERIM_DIR / "rides" / f"{climb.activity_id}.parquet")
    clean = pd.read_parquet(config.PROCESSED_DIR / "rides" / f"{climb.activity_id}.parquet")
    plot_altitude_and_grade(raw, clean, FIG / "cleaning_altitude_grade.png")
    plot_stop_durations(stops, FIG / "cleaning_stop_durations.png")

    csv = pd.read_csv(config.RAW_DIR / "activities.csv")[["Activity ID", "Elevation Gain"]]
    m = rides.merge(csv, left_on="activity_id", right_on="Activity ID")
    m = m[m["has_altitude_m"] & (m["Elevation Gain"] > 50)]
    elev_ratio = (m["elevation_gain_m"] / m["Elevation Gain"]).median()
    moving_ratio = (rides["moving_s"] / rides["moving_time_s"]).median()
    short = (stops["duration_s"] <= 120).mean()

    md = f"""# Data cleaning

Generated by `scripts/report_cleaning.py`.

Every ride keeps one row per second; cleaning adds flags and smoothed columns.

| Problem | Method |
|---|---|
| GPS spikes | Drop points more than 50 m from the 7-second rolling-median track, or implying > 90 km/h; refill gaps up to 10 s by interpolation |
| Stops (incl. device auto-pause) | A second is a stop candidate if paused, slower than 1 m/s, or missing. A run of candidates is a **stop** if the position before and after differs by < 30 m, otherwise a **recording gap while moving**. Stops < 3 s apart are merged |
| Noisy altitude | 5 s rolling median (spikes) then 15 s rolling mean (jitter) |
| Noisy grade | Grade from smoothed altitude 25 m behind and 25 m ahead on the road, clipped to ±25% |

## Checks against Strava

- Moving time: median ratio ours / Strava = **{moving_ratio:.3f}**
- Elevation gain: median ratio ours / Strava = **{elev_ratio:.2f}** (rides with > 50 m gain)
- **{len(stops):,} stop events**, {short:.0%} of them last two minutes or less (traffic-light territory)

![Altitude and grade](figures/cleaning_altitude_grade.png)

![Stop durations](figures/cleaning_stop_durations.png)
"""
    (config.REPORTS_DIR / "cleaning.md").write_text(md, encoding="utf-8")
    print(md)


if __name__ == "__main__":
    main()
